const escapeHtml = (value) =>
  String(value ?? '').replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]
  )
const money = (value, currency) => `${currency} ${Number(value || 0).toFixed(2)}`
export function monthlyReportEmail(report) {
  const { shop, period, totals } = report
  const products = (report.topProducts ?? []).slice(0, 5)
  const low = (report.lowStockProducts ?? []).slice(0, 5)
  const subject = `Shopwise Monthly Report — ${period.label}`
  const rows =
    products
      .map((p) => `<li>${escapeHtml(p.name)} — ${escapeHtml(p.quantitySold)} sold</li>`)
      .join('') || '<li>No completed sales</li>'
  const warnings =
    low
      .map((p) => `<li>${escapeHtml(p.name)} — ${escapeHtml(p.quantity)} remaining</li>`)
      .join('') || '<li>No low-stock products</li>'
  const text = `${subject}\n${shop.name}\nSales: ${money(totals.totalSales, shop.currency)}\nTransactions: ${totals.transactions}\nGross profit: ${money(totals.grossProfit, shop.currency)}\nLow-stock products: ${low.length}`
  const html = `<!doctype html><html><body style="font-family:Arial,sans-serif;color:#17202a;max-width:640px;margin:auto"><h1>${escapeHtml(shop.name)}</h1><p>${escapeHtml(period.label)} business summary</p><table cellpadding="8" style="border-collapse:collapse"><tr><td>Total sales</td><td><b>${money(totals.totalSales, shop.currency)}</b></td></tr><tr><td>Transactions</td><td><b>${escapeHtml(totals.transactions)}</b></td></tr><tr><td>Gross revenue</td><td><b>${money(totals.grossRevenue, shop.currency)}</b></td></tr><tr><td>Discounts</td><td>${money(totals.totalDiscounts, shop.currency)}</td></tr><tr><td>Tax</td><td>${money(totals.totalTax, shop.currency)}</td></tr><tr><td>Gross profit</td><td><b>${money(totals.grossProfit, shop.currency)}</b></td></tr></table><h2>Top products</h2><ul>${rows}</ul><h2>Low-stock warnings</h2><ul>${warnings}</ul><p style="color:#667;font-size:12px">Generated by Shopwise MiniPOS.</p></body></html>`
  return { subject, html, text }
}
